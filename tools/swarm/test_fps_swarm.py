def test_two_agents_claiming_together_resolve_to_one_holder() -> None:
    gh = ready_repo()
    a, b = swarm(gh, "claude-a"), swarm(gh, "claude-b")
    item_a, cards_a = a.precheck(11)
    item_b, cards_b = b.precheck(11)
    card_a = a.post_card(item_a, cards_a)
    card_b = b.post_card(item_b, cards_b)
    gh.advance(20 / 60)
    results = {
        "claude-b": b.settle(item_b, card_b),
        "claude-a": a.settle(item_a, card_a),
    }
    assert results == {"claude-a": True, "claude-b": False}
    cards = fs.cards_from_comments(gh.comments[11])
    assert [c.card.state for c in cards] == ["active", "superseded"]
    held = fs.holder(cards, gh.now)
    assert held is not None and held.card.agent == "claude-a"
    assert gh.labels(11).count("status:in-progress") == 1


def claim_in_thread(
    gh: FakeGitHub, agent: str, barrier: threading.Barrier, results: dict[str, object]
) -> None:
    """Claim #11 and meet the other claimant at the settle wait."""

    def settle_wait(_seconds: float) -> None:
        barrier.wait(timeout=5)

    s = swarm(gh, agent)
    s.sleep = settle_wait
    try:
        results[agent] = s.claim(11)
    except fs.Refused:
        results[agent] = "refused"
        settle_wait(0)


def test_concurrent_claims_in_threads_resolve_to_one_holder() -> None:
    for _ in range(20):
        gh = ready_repo()
        barrier = threading.Barrier(3)
        results: dict[str, object] = {}
        threads = [
            threading.Thread(
                target=claim_in_thread, args=(gh, f"claude-{n}", barrier, results)
            )
            for n in "ab"
        ]
        for t in threads:
            t.start()
        barrier.wait(timeout=5)
        for t in threads:
            t.join(timeout=5)
        winners = [a for a, r in results.items() if isinstance(r, fs.CardComment)]
        assert len(winners) == 1
        held = fs.holder(fs.cards_from_comments(gh.comments[11]), gh.now)
        assert held is not None and held.card.agent == winners[0]


