def make_card(**over: object) -> fs.Card:
    values: dict[str, object] = {
        "key": "OPS-02",
        "agent": "claude-a",
        "state": "active",
        "lease": T0 + dt.timedelta(minutes=90),
        "progress": "0% (0 of 6 plan steps)",
        "branch": "wp/OPS-02",
        "handoff": "docs/handoff/OPS-02.md",
    }
    values.update(over)
    return fs.Card(**values)  # type: ignore[arg-type]


