def test_stale_sweep_marks_only_expired_holders() -> None:
    gh = ready_repo()
    gh.add_issue(80, "[ENG-80] Expired", ["type:wp", "status:in-progress"])
    gh.add_issue(81, "[ENG-81] Renewed", ["type:wp", "status:in-progress"])
    post(gh, 80, make_card(key="ENG-80", lease=T0 - dt.timedelta(seconds=1)))
    post(gh, 81, make_card(key="ENG-81", lease=T0 - dt.timedelta(minutes=30)))
    post(
        gh,
        81,
        make_card(key="ENG-81", agent="claude-b", lease=T0 + dt.timedelta(minutes=60)),
    )
    gh.issues[11]["labels"] = [{"name": "type:wp"}, {"name": "status:in-progress"}]
    post(gh, 11, make_card())
    s = swarm(gh, "claude-sweep")
    assert s.stale_sweep(dry_run=True) == [80]
    assert gh.mutations() == []
    assert s.stale_sweep() == [80]
    assert "status:stale" in gh.labels(80) and "status:in-progress" not in gh.labels(80)
    assert "status:in-progress" in gh.labels(81)


def test_promotion_sweep_applies_the_three_rules() -> None:
    gh = ready_repo()
    gh.add_issue(
        90,
        "[ENG-90] Needs OPS-02 and CON-00",
        ["type:wp", "status:backlog"],
        body="- **Depends on.** OPS-02, CON-00\n",
    )
    gh.add_issue(
        91,
        "[ENG-91] Needs a dropped package",
        ["type:wp", "status:backlog"],
        body="- **Depends on.** ENG-92\n",
    )
    gh.add_issue(
        92,
        "[ENG-92] Dropped",
        ["type:wp", "status:backlog"],
        state="closed",
        state_reason="not_planned",
    )
    gh.add_issue(
        93,
        "[ENG-93] Epic",
        ["type:wp", "status:backlog", "needs:split"],
        body="- **Depends on.** none\n",
    )
    s = swarm(gh, "claude-sweep")
    assert s.promotion_sweep(dry_run=True) == [(92, "status:done")]
    assert gh.mutations() == []
    gh.close(11)
    changes = s.promotion_sweep()
    assert sorted(changes) == [
        (11, "status:done"),
        (12, "status:ready"),
        (90, "status:ready"),
        (92, "status:done"),
    ]
    assert "status:ready" in gh.labels(90) and "status:backlog" not in gh.labels(90)
    assert "status:backlog" in gh.labels(91) and "status:backlog" in gh.labels(93)
    assert "status:done" in gh.labels(92)


