"""Check, render, and seed the FixingPointSystem work package catalog.

Subcommands
  check   Validate plan/work-packages.yaml.
  render  Write docs/wiki/Work-Packages-Phase-N.md; --check fails when files are stale.
  lint    Check docs/wiki for broken links and orphan pages.
  seed    Print (default) or create (--apply) GitHub issues for work packages.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "plan" / "work-packages.yaml"
WIKI = ROOT / "docs" / "wiki"
REPO = "alrawi/FixingPointSystem"
ID_RE = re.compile(r"^([A-Z]{2,3})-(\d{2})$")
REQUIRED = ("id", "title", "phase", "workstream", "size", "depends_on", "paths",
            "summary", "deliverables", "acceptance")
# Any package may add its own CI workflow, a proposed decision record, or its handoff file.
GLOBAL_PATHS = (".github/workflows/", "docs/decisions/", "docs/handoff/", "docs/wiki/log/",
                "contracts/changes/", "mk/")
GENERATED_NOTE = ("<!-- Generated by tools/plan/plan.py render from plan/work-packages.yaml."
                  " Do not edit by hand. -->")


def load(path: Path = CATALOG) -> dict:
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def check(plan: dict) -> list[str]:
    """Return a list of error strings; an empty list means the catalog is valid."""
    errors: list[str] = []
    phases = {p["number"] for p in plan.get("phases", [])}
    streams = {w["id"]: w for w in plan.get("workstreams", [])}
    wps = plan.get("work_packages", [])
    by_id: dict[str, dict] = {}
    for wp in wps:
        wid = wp.get("id", "<missing id>")
        for key in REQUIRED:
            if key not in wp:
                errors.append(f"{wid}: missing field '{key}'")
        m = ID_RE.match(str(wid))
        if not m:
            errors.append(f"{wid}: id must look like ENG-04")
        elif m.group(1) != wp.get("workstream"):
            errors.append(f"{wid}: id prefix does not match workstream {wp.get('workstream')}")
        if wid in by_id:
            errors.append(f"{wid}: duplicate id")
        by_id[wid] = wp
        if wp.get("phase") not in phases:
            errors.append(f"{wid}: unknown phase {wp.get('phase')}")
        if wp.get("size") not in ("S", "M", "L"):
            errors.append(f"{wid}: size must be S, M, or L")
        ws = streams.get(wp.get("workstream"))
        if ws is None:
            errors.append(f"{wid}: unknown workstream {wp.get('workstream')}")
            continue
        allowed = list(ws.get("paths", [])) + list(ws.get("shared_paths", []))
        excluded = tuple(ws.get("excluded_paths", []))
        for p in wp.get("paths", []):
            if excluded and p.startswith(excluded):
                errors.append(f"{wid}: path {p} is excluded from workstream {ws['id']}")
            elif not any(p == a or p.startswith(a) for a in allowed) \
                    and not p.startswith(GLOBAL_PATHS):
                errors.append(f"{wid}: path {p} is outside workstream {ws['id']}")
    for wid, wp in by_id.items():
        for dep in wp.get("depends_on", []):
            if dep not in by_id:
                errors.append(f"{wid}: unknown dependency {dep}")
            elif by_id[dep]["phase"] > wp["phase"]:
                errors.append(f"{wid}: depends on {dep} from a later phase")
            elif dep == wid:
                errors.append(f"{wid}: depends on itself")
    errors.extend(_cycles(by_id))
    return errors


def _cycles(by_id: dict[str, dict]) -> list[str]:
    state: dict[str, int] = {}
    errors: list[str] = []

    def visit(node: str, trail: list[str]) -> None:
        state[node] = 1
        for dep in by_id[node].get("depends_on", []):
            if dep not in by_id:
                continue
            if state.get(dep) == 1:
                errors.append("dependency cycle: " + " -> ".join(trail + [node, dep]))
            elif dep not in state:
                visit(dep, trail + [node])
        state[node] = 2

    for node in sorted(by_id):
        if node not in state:
            visit(node, [])
    return errors


def dependents(plan: dict) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {wp["id"]: [] for wp in plan["work_packages"]}
    for wp in plan["work_packages"]:
        for dep in wp["depends_on"]:
            out.setdefault(dep, []).append(wp["id"])
    return out


def wp_markdown(wp: dict, heading: str = "###") -> str:
    lines = [f"{heading} {wp['id']} {wp['title']}", ""]
    tags = [f"Phase {wp['phase']}", f"size {wp['size']}", f"workstream {wp['workstream']}"]
    if wp.get("critical"):
        tags.append("critical path")
    lines.append(" · ".join(tags))
    lines.append("")
    deps = ", ".join(wp["depends_on"]) or "none"
    lines.append(f"- **Depends on.** {deps}")
    lines.append(f"- **Paths.** {', '.join('`' + p + '`' for p in wp['paths'])}")
    if wp.get("owner_action"):
        lines.append(f"- **Owner action.** {wp['owner_action']}")
    if wp["size"] == "L":
        lines.append("- **Epic.** Split this package into S or M packages before anyone claims it.")
    lines += ["", wp["summary"].strip(), "", "Deliverables.", ""]
    lines += [f"- {d}" for d in wp["deliverables"]]
    lines += ["", "Acceptance.", ""]
    lines += [f"- [ ] {a}" for a in wp["acceptance"]]
    return "\n".join(lines) + "\n"


def render_phase(plan: dict, number: int) -> str:
    phase = next(p for p in plan["phases"] if p["number"] == number)
    wps = [wp for wp in plan["work_packages"] if wp["phase"] == number]
    streams = {w["id"]: w["name"] for w in plan["workstreams"]}
    out = [GENERATED_NOTE, "", f"# Phase {number} work packages ({phase['name']})", "",
           phase["gate"].strip(), "",
           f"This page lists {len(wps)} work packages. Packages marked critical path gate the phase.",
           "Read [Swarm Protocol](Swarm-Protocol.md) before claiming one.", "",
           "## Dependency graph", "", "```mermaid", "flowchart LR"]
    for wp in wps:
        shape = f'{wp["id"].replace("-", "_")}["{wp["id"]}<br/>{wp["title"]}"]'
        out.append(f"  {shape}")
    ids = {wp["id"] for wp in wps}
    for wp in wps:
        for dep in wp["depends_on"]:
            if dep in ids:
                out.append(f"  {dep.replace('-', '_')} --> {wp['id'].replace('-', '_')}")
    crit = [wp["id"].replace("-", "_") for wp in wps if wp.get("critical")]
    if crit:
        out.append("  classDef critical stroke-width:3px")
        out.append(f"  class {','.join(crit)} critical")
    out += ["```", "", "## Summary", "", "| ID | Title | Size | Depends on | Critical |",
            "|---|---|---|---|---|"]
    for wp in wps:
        out.append(f"| [{wp['id']}](#{_anchor(wp)}) | {wp['title']} | {wp['size']} | "
                   f"{', '.join(wp['depends_on']) or 'none'} | {'yes' if wp.get('critical') else ''} |")
    out.append("")
    for ws in plan["workstreams"]:
        group = [wp for wp in wps if wp["workstream"] == ws["id"]]
        if not group:
            continue
        out += [f"## {ws['id']} {streams[ws['id']]}", ""]
        for wp in group:
            out.append(wp_markdown(wp))
    return "\n".join(out).rstrip() + "\n"


def _anchor(wp: dict) -> str:
    text = f"{wp['id']} {wp['title']}".lower()
    text = re.sub(r"[^a-z0-9 _-]", "", text)
    return text.replace(" ", "-")


def render(plan: dict, check_only: bool) -> int:
    stale = []
    for p in plan["phases"]:
        if p["number"] == 0:
            continue
        path = WIKI / f"Work-Packages-Phase-{p['number']}.md"
        text = render_phase(plan, p["number"])
        if check_only:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("stale generated pages, run `python3 tools/plan/plan.py render`:", file=sys.stderr)
        for s in stale:
            print(f"  {s}", file=sys.stderr)
        return 1
    return 0


LINK_RE = re.compile(r"\]\(([^)#\s]+\.md)(#[^)]*)?\)")


def lint(wiki: Path = WIKI) -> list[str]:
    """Report broken intra wiki links and pages that no other page links to."""
    pages = {p.name for p in wiki.glob("*.md")}
    linked: set[str] = set()
    errors = []
    for page in sorted(wiki.glob("*.md")):
        text = page.read_text(encoding="utf-8")
        for target, _ in LINK_RE.findall(text):
            if "/" in target:
                continue
            if target not in pages:
                errors.append(f"{page.name}: broken link to {target}")
            elif target != page.name:
                linked.add(target)
        for ch in ("—",):
            if ch in text:
                errors.append(f"{page.name}: contains an em dash")
    for entry in sorted((wiki / "log").glob("*.md")):
        text = entry.read_text(encoding="utf-8")
        for target, _ in LINK_RE.findall(text):
            if "/" not in target and target not in pages:
                errors.append(f"log/{entry.name}: broken link to {target}")
        if "\u2014" in text:
            errors.append(f"log/{entry.name}: contains an em dash")
    if (wiki / "log").is_dir():
        sys.path.insert(0, str(ROOT / "tools" / "wiki"))
        import build_log  # noqa: PLC0415
        errors.extend(f"log/{e}" for e in build_log.check_entries(wiki / "log"))
    for name in sorted(pages - linked - {"Home.md", "_Sidebar.md", "_Footer.md"}):
        errors.append(f"{name}: orphan page, no other page links to it")
    return errors


def paths_overlap(a: str, b: str) -> bool:
    """True when one path is the other or contains it."""
    a, b = a.rstrip("/") + "/", b.rstrip("/") + "/"
    return a.startswith(b) or b.startswith(a)


def batch(plan: dict, candidates: list[str], limit: int) -> tuple[list[str], list[tuple[str, str]]]:
    """Pick candidates in priority order so that no two picked packages share a path.

    Returns the picked ids and, for each skipped id, the picked id it collides with.
    Priority is critical path first, then lower phase, then catalog order.
    """
    by_id = {wp["id"]: wp for wp in plan["work_packages"]}
    order = {wp["id"]: i for i, wp in enumerate(plan["work_packages"])}
    ranked = sorted((c for c in candidates if c in by_id),
                    key=lambda i: (not by_id[i].get("critical"), by_id[i]["phase"], order[i]))
    picked: list[str] = []
    skipped: list[tuple[str, str]] = []
    for wid in ranked:
        if len(picked) >= limit:
            break
        clash = next((p for p in picked
                      if any(paths_overlap(a, b) for a in by_id[wid]["paths"]
                             for b in by_id[p]["paths"])), None)
        if clash:
            skipped.append((wid, clash))
        else:
            picked.append(wid)
    return picked, skipped


def ready_ids() -> list[str]:
    """Catalog ids of open work packages labeled status:ready or status:stale."""
    ids: list[str] = []
    for label in ("status:ready", "status:stale"):
        pages = gh("--paginate", "--slurp",
                   f"repos/{REPO}/issues?state=open&labels=type:wp,{label}&per_page=100")
        for page in pages or []:
            for issue in page:
                names = {lab["name"] for lab in issue["labels"]}
                m = re.match(r"^\[([A-Z]{2,3}-\d{2})\]", issue["title"])
                if m and "needs:split" not in names:
                    ids.append(m.group(1))
    return ids


def issue_body(wp: dict) -> str:
    return (f"<!-- fps:wp id={wp['id']} -->\n"
            f"Work package from the [catalog](https://github.com/{REPO}/wiki/"
            f"Work-Packages-Phase-{wp['phase']}). The catalog in `plan/work-packages.yaml` "
            "defines the scope; change scope there first.\n\n" + wp_markdown(wp, "##")
            + "\n## Coordination\n\nFollow the [Swarm Protocol]"
            f"(https://github.com/{REPO}/wiki/Swarm-Protocol). Branch `wp/{wp['id']}`, handoff file "
            f"`docs/handoff/{wp['id']}.md`.\n")


def issue_labels(wp: dict, ready: bool) -> list[str]:
    labels = ["type:wp", f"ws:{wp['workstream'].lower()}", f"phase:{wp['phase']}",
              f"size:{wp['size']}"]
    if wp.get("critical"):
        labels.append("critical-path")
    if wp.get("owner_action") or wp["workstream"] == "CON":
        labels.append("needs:owner")
    if wp["size"] == "L":
        labels += ["status:backlog", "needs:split"]
    else:
        labels.append("status:ready" if ready else "status:backlog")
    return labels


def gh(*args: str, payload: dict | None = None) -> object:
    cmd = ["gh", "api", *args]
    res = subprocess.run(cmd, input=json.dumps(payload) if payload else None,
                         capture_output=True, text=True, check=True)
    return json.loads(res.stdout) if res.stdout.strip() else None


def existing_issues() -> dict[str, dict]:
    found: dict[str, dict] = {}
    pages = gh("--paginate", "--slurp", f"repos/{REPO}/issues?state=all&labels=type:wp&per_page=100")
    for page in pages or []:
        for issue in page:
            m = re.match(r"^\[([A-Z]{2,3}-\d{2})\]", issue["title"])
            if m:
                found[m.group(1)] = issue
    return found


def seed(plan: dict, phase: int, apply: bool) -> int:
    existing = existing_issues()
    closed = {k for k, v in existing.items() if v["state"] == "closed"}
    for wp in plan["work_packages"]:
        if wp["phase"] != phase or wp["id"] in existing:
            continue
        ready = all(d in closed for d in wp["depends_on"])
        # A dependency counts as done only when its issue closed as completed.
        ready = ready and all(existing[d].get("state_reason") in (None, "completed")
                              for d in wp["depends_on"])
        title = f"[{wp['id']}] {wp['title']}"
        labels = issue_labels(wp, ready)
        if wp.get("status") == "done":
            labels = [l for l in labels if not l.startswith("status:")] + ["status:done"]
        if not apply:
            print(f"would create: {title}  labels={','.join(labels)}")
            continue
        issue = gh(f"repos/{REPO}/issues", "--method", "POST", "--input", "-",
                   payload={"title": title, "body": issue_body(wp), "labels": labels})
        if wp.get("status") == "done":
            gh(f"repos/{REPO}/issues/{issue['number']}", "--method", "PATCH", "--input", "-",
               payload={"state": "closed", "state_reason": "completed"})
            closed.add(wp["id"])
            existing[wp["id"]] = {"state": "closed", "state_reason": "completed"}
        print(f"created: #{issue['number']} {title}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check")
    r = sub.add_parser("render")
    r.add_argument("--check", action="store_true")
    sub.add_parser("lint")
    s = sub.add_parser("seed")
    s.add_argument("--phase", type=int, required=True)
    s.add_argument("--apply", action="store_true", help="create issues; without it, print only")
    b = sub.add_parser("batch", help="pick ready packages whose paths do not overlap")
    b.add_argument("--max", type=int, default=8)
    b.add_argument("ids", nargs="*", help="candidate ids; default is every ready issue on GitHub")
    args = ap.parse_args(argv)
    plan = load()
    errors = check(plan)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if args.cmd == "check":
        print(f"ok: {len(plan['work_packages'])} work packages")
        return 0
    if args.cmd == "render":
        return render(plan, args.check)
    if args.cmd == "lint":
        problems = lint()
        print("\n".join(problems) if problems else "ok: wiki links")
        return 1 if problems else 0
    if args.cmd == "batch":
        picked, skipped = batch(plan, args.ids or ready_ids(), args.max)
        for wid in picked:
            print(f"run   {wid}")
        for wid, clash in skipped:
            print(f"later {wid} (shares a path with {clash})")
        return 0
    return seed(plan, args.phase, args.apply)


if __name__ == "__main__":
    sys.exit(main())
