// Generates src/api/schema.d.ts from the controller REST contract.
//
//   node scripts/gen-api.mjs           write the file
//   node scripts/gen-api.mjs --check   fail when the committed file differs

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const contract = fileURLToPath(new URL("../../contracts/openapi/fps-api-v1.yaml", import.meta.url));
const target = fileURLToPath(new URL("../src/api/schema.d.ts", import.meta.url));

const header = [
  "// SPDX-License-Identifier: GPL-3.0-only",
  "//",
  "// Generated by scripts/gen-api.mjs from contracts/openapi/fps-api-v1.yaml.",
  "// Do not edit. Run `npm run gen:api` after a contract change.",
  "",
  "",
].join("\n");

const ast = await openapiTS(pathToFileURL(contract), { silent: true });
const generated = header + astToString(ast);

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(target, "utf8");
  } catch {
    // A missing file counts as a difference.
  }
  if (current !== generated) {
    console.error("src/api/schema.d.ts is out of date with contracts/openapi/fps-api-v1.yaml.");
    console.error("Run `npm run gen:api` in ui/ and commit the result.");
    process.exit(1);
  }
  console.log("src/api/schema.d.ts matches the contract.");
} else {
  await writeFile(target, generated);
  console.log("wrote src/api/schema.d.ts");
}
