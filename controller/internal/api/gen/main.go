// Command gen writes the generated code of package api from the OpenAPI
// contract. Package api runs it through go generate:
//
//	cd controller/internal/api && go generate .
//
// It writes two files. api.gen.go holds the types and the standard library
// server interface that oapi-codegen produces. routes.gen.go holds one route per
// operation with its method, path, and the scope from x-required-scope. The test
// TestGeneratedCodeIsCurrent fails when either file differs from what this
// command would write.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"text/template"

	"github.com/getkin/kin-openapi/openapi3"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"

	"github.com/alrawi/FixingPointSystem/controller/internal/api/contract"
)

// CodegenModule and CodegenVersion name the pinned generator. The header of
// api.gen.go carries them, and a test checks CodegenVersion against go.mod.
const (
	CodegenModule  = "github.com/oapi-codegen/oapi-codegen/v2"
	CodegenVersion = "v2.6.0"
)

// ScopeExtension is the operation extension that names the required token scope.
const ScopeExtension = "x-required-scope"

// Output file names, relative to the api package directory.
const (
	TypesFile  = "api.gen.go"
	RoutesFile = "routes.gen.go"
)

func main() {
	spec := flag.String("contract", "../../../contracts/openapi/fps-api-v1.yaml", "path of the OpenAPI contract")
	out := flag.String("out", ".", "directory of package api")
	flag.Parse()
	files, err := Generate(*spec)
	if err == nil {
		err = write(*out, files)
	}
	if err != nil {
		_, _ = fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func write(dir string, files map[string][]byte) error {
	for name, data := range files {
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o600); err != nil {
			return fmt.Errorf("write %s: %w", name, err)
		}
	}
	return nil
}

// Generate returns the generated files of package api, keyed by file name.
func Generate(specPath string) (map[string][]byte, error) {
	doc, err := contract.Load(specPath)
	if err != nil {
		return nil, err
	}
	routes, err := Routes(doc)
	if err != nil {
		return nil, err
	}
	types, err := generateTypes(doc)
	if err != nil {
		return nil, err
	}
	routesSrc, err := renderRoutes(routes)
	if err != nil {
		return nil, err
	}
	return map[string][]byte{TypesFile: types, RoutesFile: routesSrc}, nil
}

// headerRE matches the first line of oapi-codegen output, which names the
// module and version of the binary that ran it. A library call reports the
// calling module there, so we replace the line with the pinned generator.
var headerRE = regexp.MustCompile(`(?m)^// Code generated by .* DO NOT EDIT\.$`)

func generateTypes(doc *openapi3.T) ([]byte, error) {
	cfg := codegen.Configuration{
		PackageName: "api",
		Generate: codegen.GenerateOptions{
			Models:        true,
			StdHTTPServer: true,
		},
		Compatibility: codegen.CompatibilityOptions{
			// Prefix enum constants with their type, so the same value in two
			// enums, such as running or kernel, never collides.
			AlwaysPrefixEnumValues: true,
		},
	}.UpdateDefaults()
	if err := cfg.Validate(); err != nil {
		return nil, fmt.Errorf("codegen configuration: %w", err)
	}
	src, err := codegen.Generate(doc, cfg)
	if err != nil {
		return nil, fmt.Errorf("codegen: %w", err)
	}
	header := fmt.Sprintf("// Code generated by %s version %s DO NOT EDIT.", CodegenModule, CodegenVersion)
	if !headerRE.MatchString(src) {
		return nil, errors.New("codegen output has no generated code header")
	}
	src = headerRE.ReplaceAllLiteralString(src, header)
	return []byte("// SPDX-License-Identifier: GPL-3.0-only\n\n" + src), nil
}

// Route is one operation of the contract.
type Route struct {
	Method      string
	Path        string
	OperationID string
	// Handler is the method name on ServerInterface and ServerInterfaceWrapper.
	Handler string
	Scope   string
}

// Routes lists the operations of doc sorted by path and method. It fails when
// an operation lacks an operationId or a valid x-required-scope.
func Routes(doc *openapi3.T) ([]Route, error) {
	var routes []Route
	for path, item := range doc.Paths.Map() {
		for method, op := range item.Operations() {
			if op.OperationID == "" {
				return nil, fmt.Errorf("%s %s has no operationId", method, path)
			}
			scope, _ := op.Extensions[ScopeExtension].(string)
			if !slices.Contains([]string{"read", "run", "admin"}, scope) {
				return nil, fmt.Errorf("%s %s has %s %q, want read, run, or admin", method, path, ScopeExtension, scope)
			}
			routes = append(routes, Route{
				Method:      method,
				Path:        path,
				OperationID: op.OperationID,
				Handler:     codegen.UppercaseFirstCharacter(codegen.ToCamelCase(op.OperationID)),
				Scope:       scope,
			})
		}
	}
	slices.SortFunc(routes, func(a, b Route) int {
		if c := strings.Compare(a.Path, b.Path); c != 0 {
			return c
		}
		return strings.Compare(a.Method, b.Method)
	})
	return routes, nil
}

var scopeConst = map[string]string{"read": "ScopeRead", "run": "ScopeRun", "admin": "ScopeAdmin"}

var routesTmpl = template.Must(template.New("routes").Funcs(template.FuncMap{
	"scope": func(s string) string { return scopeConst[s] },
	"lower": strings.ToLower,
}).Parse(`// SPDX-License-Identifier: GPL-3.0-only

// Code generated by internal/api/gen from contracts/openapi/fps-api-v1.yaml DO NOT EDIT.

package api

import "net/http"

// operations lists every operation of the contract with its required scope.
func operations(w *ServerInterfaceWrapper) []operation {
	return []operation{
{{- range .}}
		{method: http.Method{{.Method | printf "%.1s"}}{{slice .Method 1 | lower}}, path: {{printf "%q" .Path}}, id: {{printf "%q" .OperationID}}, scope: {{scope .Scope}}, handler: w.{{.Handler}}},
{{- end}}
	}
}
`))

func renderRoutes(routes []Route) ([]byte, error) {
	var buf bytes.Buffer
	if err := routesTmpl.Execute(&buf, routes); err != nil {
		return nil, fmt.Errorf("render routes: %w", err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format routes: %w", err)
	}
	return src, nil
}
